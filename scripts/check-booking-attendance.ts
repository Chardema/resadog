import assert from "node:assert/strict";
import { buildSpecialRequests } from "../src/lib/booking-details";
import { attendanceDetails, noShowMessage, noShowTimingError, parisAppointment, reminderEvents, reminderMessage, type AttendanceBooking } from "../src/lib/booking-attendance";

const b: AttendanceBooking = { id: "booking-example", serviceType: "DAY_CARE", startDate: new Date("2026-09-12T12:00:00Z"), endDate: new Date("2026-09-14T12:00:00Z"), startTime: "08:00", endTime: "18:00", totalPrice: 105, pets: [{name:"Rex"},{name:"Luna"}], client: {name:"Client exemple",email:"example@example.com",phone:null} };
assert.equal(parisAppointment("2026-09-12", "08:00")?.toISOString(), "2026-09-12T06:00:00.000Z");
assert.equal(parisAppointment("2026-01-12", "08:00")?.toISOString(), "2026-01-12T07:00:00.000Z");
assert.equal(parisAppointment("2026-03-29", "08:00")?.toISOString(), "2026-03-29T06:00:00.000Z");
assert.equal(parisAppointment("2026-03-29", "02:30"), null);
assert.equal(parisAppointment("2026-10-25", "08:00")?.toISOString(), "2026-10-25T07:00:00.000Z");
assert.equal(parisAppointment("2026-09-12", "25:00"), null);
assert.equal(parisAppointment("2026-09-12", null), null);
const eve = new Date("2026-09-11T16:00:00Z");
const event = reminderEvents(b,eve)[0];
assert.equal(event.date,"2026-09-12");
assert.deepEqual(reminderEvents(b,eve),reminderEvents(b,new Date("2026-09-11T16:45:00Z")));
assert.equal(reminderEvents(b,new Date("2026-09-12T16:00:00Z"))[0].date,"2026-09-13");
assert.equal(reminderEvents(b,new Date("2026-09-14T16:00:00Z")).length,0);
const text = reminderMessage(b,event).text;
for(const fragment of ["08:00","18:00","29 boulevard","07.71.59.30.16","Rex, Luna","nourriture","non renseigné"]) assert.ok(text.includes(fragment),fragment);
const boarding = {...b,serviceType:"BOARDING"};
assert.equal(reminderEvents(boarding,new Date("2026-09-12T16:00:00Z")).length,0);
assert.equal(reminderEvents(boarding,new Date("2026-09-13T16:00:00Z"))[0].kind,"PICKUP");
assert.equal(reminderEvents({...boarding,endDate:b.startDate},eve)[0].kind,"REMINDER");
const home = {...b,serviceType:"DROP_IN",specialRequests:buildSpecialRequests(null,{ serviceAddress:"10 rue Exemple, Paris",visitSlots:[{date:"2026-09-12",startTime:"09:00",duration:30},{date:"2026-09-12",startTime:"18:00",duration:60}]})};
assert.equal(reminderEvents(home,eve)[0].schedule,"09:00 (30 min), 18:00 (60 min)");
assert.equal(reminderEvents(home,new Date("2026-09-12T16:00:00Z")).length,0);
assert.ok(attendanceDetails(home).includes("10 rue Exemple, Paris"));
assert.ok(!attendanceDetails(home).includes("29 boulevard"));
const cancellation = noShowMessage(b,40.5,new Date("2026-09-12T06:30:00Z")).text;
for(const fragment of ["08:30","40.50 €","Aucun remboursement","aucun nouveau prélèvement","force majeure","droits légaux"]) assert.ok(cancellation.includes(fragment),fragment);
console.log("Booking attendance: Paris/DST, daily and pickup reminders, visit slots, location/contact and cancellation copy passed.");

const single = { ...b, status: "CONFIRMED", endDate: b.startDate };
const relance = { reminderSentAt: "2026-09-12T08:10", responseDeadline: "2026-09-12T08:30" };
assert.ok(noShowTimingError(single, relance, new Date("2026-09-12T06:29:59Z")));
assert.equal(noShowTimingError(single, relance, new Date("2026-09-12T06:30:00Z")), null);
assert.ok(noShowTimingError(single, {...relance,responseDeadline:"2026-09-12T08:45"}, new Date("2026-09-12T06:30:00Z")));
assert.ok(noShowTimingError(single, {...relance,reminderSentAt:"2026-09-11T20:00"}, new Date("2026-09-12T06:30:00Z")));
assert.ok(noShowTimingError({...single,status:"IN_PROGRESS"},relance,new Date("2026-09-12T06:30:00Z")));
assert.ok(noShowTimingError({...single,serviceType:"DROP_IN"},relance,new Date("2026-09-12T06:30:00Z")));
assert.ok(noShowTimingError({...single,endDate:b.endDate},relance,new Date("2026-09-12T06:30:00Z")));
console.log("No-show: 08:30 boundary, unanswered deadline, previous-evening reminder, in-progress care and multi-day guards passed.");
